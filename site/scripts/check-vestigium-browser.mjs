import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const compiled=ts.transpileModule(fs.readFileSync('lib/vestigium-browser.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {normalizeExhibitSearch,matchesExhibit,exhibitionOrder}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const guard=JSON.parse(fs.readFileSync('public/vestigium/royal-guard.json','utf8'));
const all={query:'',abundance:'all',guardNumber:'all'};
assert.equal(normalizeExhibitSearch(' Độc Bản   HOÀNG GIA '),'doc ban hoang gia');
const pendant=guard.find(m=>m.royal_guard.relation==='representative');
assert.ok(matchesExhibit(pendant,{...all,query:'day chuyen'}));
assert.ok(matchesExhibit(pendant,{...all,query:'  DAY  CHUYEN '}));
const nine=guard.filter(m=>m.royal_guard?.number===9);
assert.ok(nine.length>0);
assert.ok(nine.every(m=>matchesExhibit(m,{...all,guardNumber:'9'})));
assert.ok(guard.filter(m=>matchesExhibit(m,{...all,guardNumber:'9'})).every(m=>m.royal_guard.number===9));
const academy=guard.filter(m=>m.royal_guard.relation==='academy');
assert.equal(academy.length,4);
assert.equal(academy.filter(m=>matchesExhibit(m,{...all,abundance:'mass-produced'})).length,0);
assert.equal(academy.filter(m=>matchesExhibit(m,{...all,guardNumber:'9'})).length,0);
const shelves=guard.filter(m=>m.royal_guard.relation==='deployment'&&matchesExhibit(m,{...all,guardNumber:'9'}));
const order=exhibitionOrder(shelves,[]);
assert.deepEqual(new Set(order.map(m=>m.id)),new Set(nine.map(m=>m.id)));
assert.ok(order.every(m=>m.royal_guard.number===9));
const full=exhibitionOrder(guard.filter(m=>m.royal_guard.relation==='deployment'),academy);
assert.deepEqual(full.slice(-4),academy);
assert.ok(!full.includes(pendant));
assert.equal(new Set(full.map(m=>m.id)).size,full.length);
assert.ok(full.slice(0,-4).every((m,i,a)=>!i||a[i-1].rarity<=m.rarity));
console.log('Passed: Vietnamese search, numbered filtering, Academy filtering, filtered pagination and shelf order.');
